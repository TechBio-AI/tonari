-- -----------------------------------------------------------------------------
-- 病気を 1 つ決める（idx と名前の両方が合えばそれ。合わなければ名前だけでちょうど 1 件。決まらなければ NULL）
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.resolve_disease_id(p_idx INTEGER, p_name TEXT)
RETURNS TEXT
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT coalesce(
        (SELECT c.disease_id FROM public.disease_catalog c WHERE c.idx = p_idx AND c.name = p_name),
        (SELECT min(c.disease_id) FROM public.disease_catalog c WHERE c.name = p_name
          HAVING count(*) = 1));
$$;

COMMENT ON FUNCTION public.resolve_disease_id(INTEGER, TEXT) IS
'idx と名前から disease_id を決める（内部用）。両方合えばそれ、名前だけでちょうど 1 件ならそれ、決まらなければ NULL';

