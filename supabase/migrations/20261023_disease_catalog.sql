'疾患の固定 ID。トリガー sync_public_wish_count が group_wishes.disease_id を写す（disease_catalog に無い idx なら NULL）';

-- 写すときに disease_id も入れる（20261019 の本文に disease_id の受け渡しを足しただけ。数え方・伏せ方・updated_at の扱いは同じ）
CREATE OR REPLACE FUNCTION public.sync_public_wish_count()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_idx INTEGER;
    v_did TEXT;
    v_cnt INTEGER;
    v_n   TEXT;
BEGIN
    FOR v_idx, v_did IN
        SELECT DISTINCT x.idx, x.did
          FROM (VALUES (CASE WHEN TG_OP <> 'INSERT' THEN OLD.disease_idx END, CASE WHEN TG_OP <> 'INSERT' THEN OLD.disease_id END),
                       (CASE WHEN TG_OP <> 'DELETE' THEN NEW.disease_idx END, CASE WHEN TG_OP <> 'DELETE' THEN NEW.disease_id END)) AS x(idx, did)
         WHERE x.idx IS NOT NULL
    LOOP
        SELECT count(*) INTO v_cnt
          FROM public.group_wishes w
         WHERE w.disease_idx = v_idx AND w.withdrawn_at IS NULL;

        v_n := CASE WHEN v_cnt < public.stats_threshold() THEN '10未満' ELSE v_cnt::TEXT END;

        INSERT INTO public.public_wish_counts AS c (disease_idx, n, updated_at, disease_id)
        VALUES (v_idx, v_n, now(), v_did)
        ON CONFLICT (disease_idx) DO UPDATE
            SET n = EXCLUDED.n, updated_at = now()
            WHERE c.n IS DISTINCT FROM EXCLUDED.n;

        -- disease_id は時刻を変えずに埋める（「10未満」のままの増減を時刻から読ませない約束はそのまま）
        UPDATE public.public_wish_counts c
           SET disease_id = v_did
         WHERE c.disease_idx = v_idx AND c.disease_id IS NULL AND v_did IS NOT NULL;
    END LOOP;

    RETURN NULL;
END;
$$;

