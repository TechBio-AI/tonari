ALTER TABLE public.patient_groups
    ADD COLUMN IF NOT EXISTS disease_ids TEXT[] NOT NULL DEFAULT '{}';

UPDATE public.patient_groups g
   SET disease_ids = r.ids
  FROM (
        SELECT g2.id,
               array_agg(public.resolve_disease_id(x.idx, x.name) ORDER BY x.ord) AS ids,
               bool_and(public.resolve_disease_id(x.idx, x.name) IS NOT NULL) AS all_found
          FROM public.patient_groups g2
          CROSS JOIN LATERAL unnest(g2.disease_idxs, g2.disease_names) WITH ORDINALITY AS x(idx, name, ord)
         GROUP BY g2.id
       ) r
 WHERE r.id = g.id AND r.all_found AND cardinality(g.disease_ids) = 0;

COMMENT ON COLUMN public.patient_groups.disease_ids IS
'会の対象の病気（疾患の固定 ID）。disease_idxs・disease_names と同じ順。空のまま会を作るとトリガーが埋める';

-- 以後、disease_ids が空のまま会を作った・病気を変えたときに、disease_idxs・disease_names から埋める
CREATE OR REPLACE FUNCTION public.fill_patient_group_disease_ids()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_ids TEXT[];
BEGIN
    IF cardinality(NEW.disease_ids) = 0 AND cardinality(NEW.disease_idxs) > 0 THEN
        SELECT array_agg(public.resolve_disease_id(x.idx, x.name) ORDER BY x.ord) INTO v_ids
          FROM unnest(NEW.disease_idxs, NEW.disease_names) WITH ORDINALITY AS x(idx, name, ord);
        -- 決まらない病気が 1 つでもあれば埋めない（推測で埋めない）
        IF array_position(v_ids, NULL) IS NULL THEN
            NEW.disease_ids := v_ids;
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS fill_patient_group_disease_ids ON public.patient_groups;
CREATE TRIGGER fill_patient_group_disease_ids
    BEFORE INSERT OR UPDATE ON public.patient_groups
    FOR EACH ROW EXECUTE FUNCTION public.fill_patient_group_disease_ids();

