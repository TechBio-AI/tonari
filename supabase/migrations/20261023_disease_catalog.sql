-- 決まらなかった行の数（NOTICE。止めはしない）
-- -----------------------------------------------------------------------------
DO $$
DECLARE
    v_wishes  BIGINT;
    v_counts  BIGINT;
    v_md      BIGINT;
    v_groups  BIGINT;
BEGIN
    SELECT count(*) INTO v_wishes FROM public.group_wishes WHERE disease_id IS NULL;
    SELECT count(*) INTO v_counts FROM public.public_wish_counts WHERE disease_id IS NULL;
    SELECT count(*) INTO v_md     FROM public.member_diseases WHERE disease_id IS NULL;
    SELECT count(*) INTO v_groups FROM public.patient_groups
     WHERE cardinality(disease_ids) <> cardinality(disease_idxs);
    RAISE NOTICE 'disease_id が決まらなかった行: group_wishes %、public_wish_counts %、member_diseases %、patient_groups %',
        v_wishes, v_counts, v_md, v_groups;
END;
$$;


-- =============================================================================
-- 3. 運営向けの参加希望の内訳（API から呼べる）
--   wish_summary（20261019。Studio 専用・disease_idx で引く）と同じ中身を、disease_id で引き、運営だけに返す。
--   取り消していない希望を、都道府県・続柄・会員かどうか（未回答は NULL）ごとの実数で返す。user_id は返さない
-- =============================================================================
CREATE OR REPLACE FUNCTION public.wish_summary_ops(p_disease_id TEXT)
RETURNS TABLE (prefecture TEXT, relation TEXT, is_group_member BOOLEAN, n BIGINT)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
#variable_conflict use_column
BEGIN
    IF auth.uid() IS NULL THEN
        RAISE EXCEPTION USING MESSAGE = 'unauthenticated';
    END IF;
    IF NOT public.is_operator() THEN
        RAISE EXCEPTION USING MESSAGE = 'forbidden';
    END IF;

    RETURN QUERY
        SELECT w.prefecture, w.relation, w.is_group_member, count(*)
          FROM public.group_wishes w
         WHERE w.disease_id = p_disease_id AND w.withdrawn_at IS NULL
         GROUP BY w.prefecture, w.relation, w.is_group_member
         ORDER BY w.prefecture, w.relation, w.is_group_member NULLS LAST;
END;
$$;

COMMENT ON FUNCTION public.wish_summary_ops(TEXT) IS
'運営向け（API から呼べる）。病気ごとの参加希望の内訳（都道府県・続柄・会員かどうか）を実数で返す。運営以外は forbidden。user_id は返さない';


