-- =============================================================================
-- 疾患の固定 ID：disease_catalog と、既存の表への disease_id の追加（共通契約 2026-10-03 の A）
--
-- ※ Claude Code は適用しない。ファウンダーがローカル Supabase で適用する。
-- ※ 20261019（group_wishes・public_wish_counts）と 20261022（operators・is_operator）の後、20261024〜20261026 の前に当てる。
--
-- 作るもの・変えるもの:
--   1. disease_catalog(disease_id 主キー, idx, name)
--        data/disease_ids.json（疾患概要担当。stable_id・idx・主名・orpha_code）から機械で作った INSERT で seed する。
--        生成: python3 scripts/portal/gen_disease_catalog.py --write（--check で、この migration と差分が無いことを確かめる）。
--        disease_id は以後不変・再利用なし。idx・name は作成時（2026-10-03）の値で、知識ファイルの並びが変わっても追いかけない。
--        認証済みの人が読める（病気の名前の参照用。個人の情報は無い）。anon は読めない（公開面は公開用の表だけを読む）。
--   2. group_wishes.disease_id          … idx から埋める。以後の insert・idx の変更では、トリガーが idx から埋める
--   3. public_wish_counts.disease_id    … idx から埋める。以後はトリガー sync_public_wish_count が写す
--   4. member_diseases.disease_id       … idx と名前から埋める（下の「埋め方」）。以後の書き込みで disease_id を入れるのは
--                                          同意担当の 20261029（この migration は同意の画面・関数に触れない）
--   5. patient_groups.disease_ids       … disease_idxs・disease_names から埋める。以後、disease_ids が空のまま会を作ったときは、
--                                          トリガーが disease_idxs から埋める
--   6. wish_summary_ops(disease_id)     … 運営が API から呼べる参加希望の内訳（実数）。運営以外は forbidden。
--                                          Studio 専用の wish_summary(disease_idx)（20261019）はそのまま残す
--   idx の列（group_wishes.disease_idx・public_wish_counts.disease_idx・member_diseases.disease_idx・
--   patient_groups.disease_idxs）はすべて残す（画面の切り替え後に外す。共通契約 A）。
--
-- 埋め方（いまある行）:
--   group_wishes・public_wish_counts … disease_idx = disease_catalog.idx で引く（この表には病名が無い）
--   member_diseases …… idx と名前（disease_name = catalog.name）の両方が合えばその病気。合わなければ名前だけで
--                       ちょうど 1 件合う病気。それでも決まらなければ NULL のまま残す（推測で埋めない）
--   patient_groups …… disease_idxs と disease_names を同じ位置で突き合わせ、member_diseases と同じ規則で引く。
--                       決まらない病気が 1 つでもある会は disease_ids を空のまま残す
--   決まらなかった行の数は NOTICE で出す（2026-10-03 に Claude Code が作業ツリーで照合した限りでは、
--   知識ファイルと disease_ids.json の名前の食い違いは 0 件、seed 済みの 7 団体も全件一致）。
--
-- Claude Code の判断（契約に無いもの）:
--   - disease_catalog.idx は一意。disease_id は rd + 5 桁
--   - group_wishes に (disease_id, user_id) の一意制約を足す（idx を外した後も 1 人 1 病気 1 件を保つ）
--   - group_wishes の idx が disease_catalog に無いとき（確認台本の架空の idx など）は disease_id を NULL のまま入れる
--     （20261019 の「disease_idx は 0 以上の整数」をそのまま保つ）
--   - patient_groups に disease_ids を埋めるトリガーを付ける（SQL で会を足したときにも埋まるように）
--
-- 権限:
--   関数は SECURITY DEFINER・search_path ''。wish_summary_ops は PUBLIC と anon に EXECUTE なし・authenticated にあり。
--   トリガー関数は API ロールのどれにも EXECUTE を与えない（既存と同じ）。
-- =============================================================================


-- =============================================================================
-- 1. disease_catalog
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.disease_catalog (
    disease_id TEXT PRIMARY KEY CHECK (disease_id ~ '^rd[0-9]{5}$'),
    idx        INTEGER NOT NULL UNIQUE CHECK (idx >= 0),
    name       TEXT NOT NULL CHECK (btrim(name) <> '')
);

COMMENT ON TABLE public.disease_catalog IS
'疾患の固定 ID（stable_id）と、作成時の知識ファイル上の位置・主名。data/disease_ids.json から生成（scripts/portal/gen_disease_catalog.py）。disease_id は不変・再利用なし';
COMMENT ON COLUMN public.disease_catalog.idx IS
'作成時（2026-10-03）の知識ファイル上の位置。以後の並び替えでは追いかけない';

ALTER TABLE public.disease_catalog ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.disease_catalog FROM anon, authenticated;

DROP POLICY IF EXISTS disease_catalog_select_authenticated ON public.disease_catalog;
CREATE POLICY disease_catalog_select_authenticated ON public.disease_catalog
    FOR SELECT TO authenticated
    USING (true);
GRANT SELECT ON public.disease_catalog TO authenticated;

