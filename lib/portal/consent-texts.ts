/** その種類の、いまの版（配列の末尾） */
export function currentConsentText(
  kind: ConsentKind,
  texts: Readonly<Record<ConsentKind, readonly ConsentText[]>> = CONSENT_TEXTS
): ConsentText {
  const list = texts[kind]
  return list[list.length - 1]
}

/** 版番号から文を引く。無い版なら null（想像で埋めない） */
export function consentTextOf(
  kind: ConsentKind,
  version: number,
  texts: Readonly<Record<ConsentKind, readonly ConsentText[]>> = CONSENT_TEXTS
): ConsentText | null {
  return texts[kind].find((t) => t.version === version) ?? null
}

/** チェック欄に出す文 */
export function consentLabelOf(t: ConsentText): string {
  return t.label ?? t.text
}
